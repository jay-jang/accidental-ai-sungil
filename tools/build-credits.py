#!/usr/bin/env python3
"""Merge assets/img/credits-*.json into js/credits-data.js (window.CREDITS) so the
credits frame works when index.html is opened straight from disk (file://)."""
import glob, json, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
items, seen = [], set()
for path in sorted(glob.glob(os.path.join(root, 'assets/img/credits-*.json'))):
    with open(path, encoding='utf-8') as fh:
        for c in json.load(fh):
            f = c.get('file') or f"assets/img/{c.get('id')}.jpg"
            if c.get('id') in seen or not os.path.exists(os.path.join(root, f)):
                continue
            seen.add(c.get('id'))
            items.append({k: c.get(k) for k in ('id', 'file', 'subject', 'author', 'license', 'source', 'year_of_photo')})
items.sort(key=lambda c: (c.get('subject') or '').lower())
with open(os.path.join(root, 'js/credits-data.js'), 'w', encoding='utf-8') as out:
    out.write('/* generated by tools/build-credits.py — image credits (Wikimedia Commons) */\n')
    out.write('window.CREDITS = ' + json.dumps(items, ensure_ascii=False, indent=1) + ';\n')
print(len(items), 'credits written')
